CREATE TABLE usuarios (
    id_usuario     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(50)  NOT NULL,
    sobrenome      VARCHAR(80)  NOT NULL,
    email          VARCHAR(100) NOT NULL UNIQUE,
    senha_hash     VARCHAR(255) NOT NULL,
    cpf            CHAR(11)     NOT NULL UNIQUE,
    telefone       VARCHAR(11)  NOT NULL,
    criado_em      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE enderecos (
    id_endereco    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario     INT          NOT NULL,
    apelido        VARCHAR(30)  NOT NULL DEFAULT 'Minha casa',
    cep            CHAR(8)      NOT NULL,
    rua            VARCHAR(100) NOT NULL,
    numero         VARCHAR(10)  NOT NULL,
    complemento    VARCHAR(50),
    bairro         VARCHAR(60)  NOT NULL,
    cidade         VARCHAR(60)  NOT NULL,
    uf             CHAR(2)      NOT NULL,
    referencia     VARCHAR(100),
    frete          DECIMAL(8,2) NOT NULL DEFAULT 0.00,
    CONSTRAINT fk_end_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuarios(id_usuario) ON DELETE CASCADE
);

CREATE TABLE cartoes (
    id_cartao      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario     INT         NOT NULL,
    bandeira       VARCHAR(20) NOT NULL,
    ultimos4       CHAR(4)     NOT NULL,
    nome_titular   VARCHAR(80) NOT NULL,
    validade       CHAR(5)     NOT NULL,   -- MM/AA
    CONSTRAINT fk_cartao_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuarios(id_usuario) ON DELETE CASCADE
);

CREATE TABLE categorias (
    id_categoria   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(40) NOT NULL UNIQUE
);

CREATE TABLE produtos (
    id_produto     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_categoria   INT          NOT NULL,
    nome           VARCHAR(60)  NOT NULL,
    descricao      VARCHAR(255) NOT NULL,
    preco          DECIMAL(8,2) NOT NULL,
    imagem_url     VARCHAR(255),
    ativo          BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_prod_categoria FOREIGN KEY (id_categoria)
        REFERENCES categorias(id_categoria)
);
CREATE INDEX idx_prod_nome ON produtos (nome);

CREATE TABLE carrinho_itens (
    id_usuario     INT NOT NULL,
    id_produto     INT NOT NULL,
    quantidade     INT NOT NULL DEFAULT 1,
    PRIMARY KEY (id_usuario, id_produto),
    CONSTRAINT fk_car_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuarios(id_usuario) ON DELETE CASCADE,
    CONSTRAINT fk_car_produto FOREIGN KEY (id_produto)
        REFERENCES produtos(id_produto),
    CONSTRAINT chk_car_qtd CHECK (quantidade > 0)
);

CREATE TABLE pedidos (
    id_pedido       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario      INT          NOT NULL,
    id_endereco     INT          NOT NULL,
    id_cartao       INT          NULL,
    forma_pagamento VARCHAR(10)  NOT NULL
        CHECK (forma_pagamento IN ('cartao','pix','dinheiro')),
    status          VARCHAR(20)  NOT NULL DEFAULT 'confirmado'
        CHECK (status IN ('confirmado','em_preparo','pronto','saiu_para_entrega','entregue','cancelado')),
    subtotal        DECIMAL(8,2) NOT NULL,
    frete           DECIMAL(8,2) NOT NULL,
    total           DECIMAL(8,2) NOT NULL,
    criado_em       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ped_usuario  FOREIGN KEY (id_usuario)  REFERENCES usuarios(id_usuario),
    CONSTRAINT fk_ped_endereco FOREIGN KEY (id_endereco) REFERENCES enderecos(id_endereco),
    CONSTRAINT fk_ped_cartao   FOREIGN KEY (id_cartao)   REFERENCES cartoes(id_cartao)
);

CREATE TABLE itens_pedido (
    id_pedido       INT          NOT NULL,
    id_produto      INT          NOT NULL,
    quantidade      INT          NOT NULL,
    preco_unitario  DECIMAL(8,2) NOT NULL,
    PRIMARY KEY (id_pedido, id_produto),
    CONSTRAINT fk_item_pedido  FOREIGN KEY (id_pedido)  REFERENCES pedidos(id_pedido) ON DELETE CASCADE,
    CONSTRAINT fk_item_produto FOREIGN KEY (id_produto) REFERENCES produtos(id_produto),
    CONSTRAINT chk_item_qtd CHECK (quantidade > 0)
);

